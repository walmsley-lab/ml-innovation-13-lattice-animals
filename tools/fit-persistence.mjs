// Fits the probability that a foreign cell is still occupied at round end, from
// archived play, and writes it where the planner can load it.
//
//   node tools/fit-persistence.mjs [--out data/foreign-persistence.json]
//
// The planner bets on foreign cells whenever it plans a formation it cannot fill
// alone. A single reliability constant is wrong at both ends of a round: early on
// a foreign unit is passing through, late it has settled. Blush splits that
// further, because a colour identifies one opponent within a game.
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { listRecords, readRecord } from './archive.mjs';

const argumentAfter = flag => {
  const index = process.argv.indexOf(flag);
  return index > -1 ? process.argv[index + 1] : undefined;
};
const runsDirectory = resolve(argumentAfter('--runs') ?? process.env.LATTICE_RUNS ?? 'runs');
// Written as a module, not data, so the kit installer carries it with the planner.
const out = resolve(argumentAfter('--out') ?? 'src/persistence.js');
const MIN_SAMPLES = 400;

// Upper bound of each turns-remaining bucket; the last bucket is everything above.
const BOUNDS = [8, 20, 40];
const bucketFor = turnsLeft => {
  for (let index = 0; index < BOUNDS.length; index++) if (turnsLeft <= BOUNDS[index]) return index;
  return BOUNDS.length;
};

const counts = new Map();
const tally = (colour, bucket, held) => {
  if (!counts.has(colour)) counts.set(colour, Array.from({ length: BOUNDS.length + 1 }, () => ({ n: 0, held: 0 })));
  const cell = counts.get(colour)[bucket];
  cell.n++;
  if (held) cell.held++;
};

let games = 0;
let rounds = 0;
for (const name of await listRecords(runsDirectory)) {
  const record = await readRecord(runsDirectory, name);
  if (record.gameId.startsWith('local')) continue;
  const log = record.replay?.log;
  if (!log?.turns?.length) continue;
  games++;
  for (const round of (log.rounds ?? []).filter(entry => entry.completed)) {
    rounds++;
    const final = new Set(log.turns[round.endTurn].units.map(unit => `${unit.x},${unit.y}`));
    for (let turn = round.startTurn; turn < round.endTurn; turn += 2) {
      const bucket = bucketFor(round.endTurn - turn);
      for (const unit of log.turns[turn].units) {
        tally(unit.blush ?? '', bucket, final.has(`${unit.x},${unit.y}`));
      }
    }
  }
}

const rate = cell => cell.n ? cell.held / cell.n : null;
const series = cells => cells.map(cell => cell.n >= MIN_SAMPLES ? Number(rate(cell).toFixed(4)) : null);

const fallback = series(counts.get('') ?? []);
const colours = {};
for (const [colour, cells] of counts) {
  if (!colour) continue;
  const values = series(cells);
  // Keep a colour only where it says something the default does not.
  if (values.every(value => value === null)) continue;
  colours[colour] = values;
}

const table = {
  generatedFrom: { games, rounds, minSamples: MIN_SAMPLES },
  bounds: BOUNDS,
  fallback,
  colours,
};
const source = `'use strict';
// Generated by tools/fit-persistence.mjs from ${games} archived games. Do not edit.
//
// P(a cell occupied now is still occupied at round end), indexed by turns
// remaining: ${BOUNDS.map((b, i) => `<=${b}`).join(', ')}, then above ${BOUNDS.at(-1)}.
// A foreign cell is a bet, and the odds move through a round: early the unit is
// passing through, late it has settled. Blush narrows it further, because within
// one game a colour belongs to one opponent.

const TABLE = ${JSON.stringify(table, null, 2)};

const bucketFor = turnsLeft => {
  for (let index = 0; index < TABLE.bounds.length; index++) {
    if (turnsLeft <= TABLE.bounds[index]) return index;
  }
  return TABLE.bounds.length;
};

/** Probability a foreign cell of this colour is still there at round end. */
function persistence(blush, turnsLeft, fallback = 0.8) {
  const bucket = bucketFor(turnsLeft);
  const series = (blush && TABLE.colours[blush]) || TABLE.fallback;
  return series?.[bucket] ?? TABLE.fallback?.[bucket] ?? fallback;
}

module.exports = { persistence, TABLE };
`;
await writeFile(out, source);
console.log(`Fitted from ${games} games, ${rounds} rounds -> ${out}`);
console.log(`  default        ${fallback.map(v => v === null ? '  —  ' : v.toFixed(3)).join('  ')}   (<=8, <=20, <=40, 40+ turns left)`);
for (const [colour, values] of Object.entries(colours)) {
  console.log(`  ${colour.padEnd(14)} ${values.map(v => v === null ? '  —  ' : v.toFixed(3)).join('  ')}`);
}
